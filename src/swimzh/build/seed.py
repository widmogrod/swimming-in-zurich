"""The seed loader: assemble the DB-enforced identity spine from committed inputs.

The catalog is the **roster authority** — every one of the ~57 published pools becomes one
``pool`` row, its canonical id minted once as ``PoolId(catalog.pool_id)`` (already the name
slug, per S1). Curated authoring layers on top: a hand-authored ``kind`` overrides the WFS
``kind`` (curated-wins — e.g. *Wärmebad Käferberg* is ``thermal`` here, not the WFS ``indoor``),
and the curated schedule payload rides along as a typed blob. Curation is **not** stored: it is
derived at read from that blob (``codec.is_curated`` — ``curated`` iff ≥1 basin with ≥1 rule),
so the status can never desync from the schedule fact it describes.

Every *other* identifier becomes a value pointing at the canonical id: names/aliases →
``pool_alias`` rows (deduped by ``norm``), external keys (crowdmonitor, geo_sport) →
``pool_xref`` rows. Those, plus the curated basins' hint index, are the ``Crosswalk`` that
``reconcile.resolve`` consults.

``PoolId`` is minted in exactly two places — here and ``build/reconcile`` — guarded by a
grep test. See ``docs/concepts/data-layer-architecture.md`` §3 for the enforcement model.
"""

from __future__ import annotations

from dataclasses import replace

from swimzh.build.reconcile import Crosswalk
from swimzh.core.normalize import normalize
from swimzh.domain.catalog import PoolCatalogEntry
from swimzh.domain.models import (
    BasinId,
    Facility,
    PoolId,
    PoolIdentity,
    PoolKind,
    Provenance,
)
from swimzh.domain.registry import Registry
from swimzh.providers.infrastruktur import (
    basin_from_physical,
    parse_features,
    parse_infrastruktur,
)
from swimzh.storage import codec
from swimzh.storage.rows import PoolAliasRow, PoolRow, PoolSpine, PoolXrefRow

_PROSE_SOURCE = "infrastruktur"
_LOCATION_SOURCE = "catalog"


def build_spine(
    catalog: tuple[PoolCatalogEntry, ...],
    facilities: tuple[Facility, ...],
    registry: Registry,
) -> PoolSpine:
    """Fold the roster (catalog) + curated authoring (facilities, registry) into the spine.

    Deterministic: rows are emitted in catalog order, aliases/xrefs deduped by their unique
    keys so the DB ``UNIQUE`` constraints are satisfiable and a re-build yields equal rows.
    """
    curated_by_id: dict[str, Facility] = {str(f.identity.facility_id): f for f in facilities}

    pools: list[PoolRow] = []
    aliases: list[PoolAliasRow] = []
    xrefs: list[PoolXrefRow] = []
    seen_norms: set[str] = set()
    seen_xrefs: set[tuple[str, str]] = set()

    for entry in sorted(catalog, key=lambda e: e.pool_id):
        pool_id = PoolId(entry.pool_id)
        identity = registry.get(pool_id)
        facility = curated_by_id.get(entry.pool_id)

        # Geo parity, not geo rescue: stamp the authoritative committed-catalog (= WFS) geo onto
        # the curated facility before it is serialized into `facility_doc`, so the offline read
        # path serves the authoritative WFS coordinates. Offline — the catalog entry comes from
        # the committed `catalog.json` (regenerated by `build-catalog`), never a live WFS merge.
        # Curated pools absent from the catalog keep their YAML geo (the `or facility.geo`
        # fallback).
        if facility is not None:
            facility = replace(facility, geo=entry.geo or facility.geo)

        # Curated-wins on kind: a hand-authored registry kind (richer/verified) overrides the
        # generic WFS catalog kind; catalog is the authority only where no curation exists.
        kind = identity.kind if identity is not None else entry.kind

        # Curated pool -> serialize its curated facility. Otherwise mint a SCHEDULE-LESS
        # location-only facility so EVERY catalog pool has a non-NULL `facility_doc` (a viewable
        # `/pools/{id}` detail — no 404). Best-effort WFS `infrastruktur` prose (on
        # `entry.description`) supplies PARSED_PROSE basins + amenity Features when it names any;
        # a pool whose prose names none (e.g. an outdoor pin like Freibad Heuried) gets a
        # location-only facility with ZERO basins. Either way it stays uncurated and yields no
        # `/swim` option (no basin has a rule). Offline, from committed inputs only; `PoolId` is
        # minted here (an allowed seam), exactly as for the curated rows.
        facility_doc: str
        if facility is not None:
            facility_doc = codec.dumps(facility)
        else:
            facility_doc = codec.dumps(_location_only_facility(entry, pool_id, kind, identity))

        pools.append(
            PoolRow(
                id=pool_id,
                name=entry.name,
                kind=kind,
                address=entry.address,
                geo=entry.geo,
                url=entry.url,
                description=entry.description,
                phone=entry.phone,
                facility_doc=facility_doc,
            )
        )

        # Aliases: catalog name + registry name/aliases, deduped by normalized key.
        alias_terms = [entry.name]
        if identity is not None:
            alias_terms.extend((identity.name, *identity.aliases))
        for term in alias_terms:
            key = normalize(term)
            if key in seen_norms:
                continue
            seen_norms.add(key)
            aliases.append(PoolAliasRow(pool_id=pool_id, alias=term, norm=key))

        # Xrefs: external namespace keys pointing at this pool.
        if identity is not None:
            ext: list[tuple[str, str]] = []
            if identity.geo_sport_id is not None:
                ext.append(("geo_sport", identity.geo_sport_id))
            ext.extend(("crowdmonitor", key) for key in identity.crowdmonitor_keys)
            for namespace, ext_id in ext:
                if (namespace, ext_id) in seen_xrefs:
                    continue
                seen_xrefs.add((namespace, ext_id))
                xrefs.append(PoolXrefRow(pool_id=pool_id, namespace=namespace, ext_id=ext_id))

    return PoolSpine(pools=tuple(pools), aliases=tuple(aliases), xrefs=tuple(xrefs))


def _location_only_facility(
    entry: PoolCatalogEntry,
    pool_id: PoolId,
    kind: PoolKind,
    identity: PoolIdentity | None,
) -> Facility:
    """Mint a schedule-less ``Facility`` for a catalog pool that has no curated schedule, so
    every roster pool has a non-NULL ``facility_doc`` and a viewable ``/pools/{id}`` detail —
    WITHOUT becoming a ``/swim`` option or flipping to ``curated``.

    Basins are best-effort from the pool's WFS ``infrastruktur`` prose (``entry.description``)
    when it names swimmable basins (schedule-less ``PARSED_PROSE``); a pool whose prose names
    none (an outdoor pin like *Freibad Heuried*, whose catalog description is the literal
    ``"NULL"``) gets a **location-only** facility with ZERO basins. Either way every basin is
    rule-less, so ``codec.is_curated`` stays False and ``find_swim_options`` yields no option
    (it ``continue``s on ``not basin.rules``) and no spurious "closed" status — the uncurated
    invariant holds.

    Identity is the **registry** identity when the pool has a registry entry, so external keys
    (crowdmonitor today, ``baditicker_poiid`` next) survive onto an *uncurated* pool's facility
    identity — falling back to the bare ``PoolIdentity(facility_id, name, kind)`` only when no
    registry entry exists. Geo is stamped from the committed catalog (parity with the curated
    path). Offline, from committed inputs only.
    """
    prose = entry.description
    physicals = parse_infrastruktur(prose) if prose is not None else ()
    basins = tuple(
        basin_from_physical(physical, BasinId(f"{entry.pool_id}-prose-{index}"))
        for index, physical in enumerate(physicals)
    )
    features = parse_features(prose) if prose is not None else ()
    mint_identity = (
        identity
        if identity is not None
        else PoolIdentity(facility_id=pool_id, name=entry.name, kind=kind)
    )
    # Honest provenance: a prose-derived facility credits `infrastruktur`; a pure location-only
    # pool (no prose basins/features) credits the `catalog` it was minted from.
    source = _PROSE_SOURCE if basins or features else _LOCATION_SOURCE
    return Facility(
        identity=mint_identity,
        address=entry.address,
        provenance=Provenance(source=source, curated=False),
        basins=basins,
        geo=entry.geo,
        features=features,
    )


def build_crosswalk(spine: PoolSpine) -> Crosswalk:
    """The lookup tables ``reconcile.resolve`` consults, built from the identity spine."""
    xref = {(x.namespace, x.ext_id): x.pool_id for x in spine.xrefs}
    alias = {a.norm: a.pool_id for a in spine.aliases}
    return Crosswalk(xref=xref, alias=alias)
